import { createHash } from 'node:crypto'
import { access, mkdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'

const displays = new Set(['standalone', 'minimal-ui', 'fullscreen', 'browser'])
const orientations = new Set(['any', 'natural', 'portrait', 'landscape'])
const isRootPath = (value) => typeof value === 'string' && value.startsWith('/') && !value.startsWith('//') && !/[?#\\]/.test(value) && !value.split('/').includes('..')
const escapeHtml = (value) => String(value).replace(/[&<>"']/g, (character) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[character])

export async function preparePwa({ pwa, siteId, publicSource, generatedPublic, generatedFiles, writeIfChanged }) {
  if (!pwa || pwa.enabled !== true) return
  const fail = (message) => { throw new Error(`Invalid PWA configuration in spmpst.pwa.json: ${message}`) }
  if (typeof pwa.name !== 'string' || !pwa.name.trim()) fail('name is required when enabled is true')
  if (typeof pwa.shortName !== 'string' || !pwa.shortName.trim() || pwa.shortName.length > 32) fail('shortName is required and must be at most 32 characters')
  if (typeof pwa.description !== 'string' || !pwa.description.trim()) fail('description is required when enabled is true')
  const scope = pwa.scope ?? '/'
  const startUrl = pwa.startUrl ?? scope
  if (!isRootPath(scope) || !scope.endsWith('/')) fail('scope must be an absolute path ending in /')
  if (!isRootPath(startUrl) || !startUrl.startsWith(scope)) fail('startUrl must be an absolute path inside scope')
  const display = pwa.display ?? 'standalone'
  if (!displays.has(display)) fail('display must be standalone, minimal-ui, fullscreen, or browser')
  const orientation = pwa.orientation ?? 'any'
  if (!orientations.has(orientation)) fail('orientation must be any, natural, portrait, or landscape')
  for (const [key, value] of [['themeColor', pwa.themeColor], ['backgroundColor', pwa.backgroundColor]]) {
    if (value !== undefined && (typeof value !== 'string' || !/^#[0-9a-f]{3,8}$/i.test(value))) fail(`${key} must be a hexadecimal color`)
  }
  if (!Array.isArray(pwa.icons) || pwa.icons.length === 0) fail('icons must be a non-empty array')
  for (const [index, icon] of pwa.icons.entries()) {
    if (!icon || typeof icon !== 'object' || !isRootPath(icon.src) || !/^\d+x\d+$/.test(icon.sizes ?? '')) fail(`icons[${index}] needs an absolute src and sizes such as 192x192`)
    const iconFile = resolve(publicSource, `.${icon.src}`)
    if (!iconFile.startsWith(`${resolve(publicSource)}/`)) fail(`icons[${index}].src must remain inside the site's public directory`)
    try { await access(iconFile) } catch { fail(`icon file was not found: ${icon.src}`) }
  }
  const excludePaths = pwa.excludePaths ?? ['/account/', '/api/']
  if (!Array.isArray(excludePaths) || excludePaths.some((path) => !isRootPath(path))) fail('excludePaths must contain absolute URL paths')
  const manifestPath = `${scope}manifest.webmanifest`
  const workerPath = `${scope}service-worker.js`
  const offlinePath = `${scope}offline.html`
  const manifest = {
    id: startUrl,
    name: pwa.name.trim(),
    short_name: pwa.shortName.trim(),
    description: pwa.description.trim(),
    start_url: startUrl,
    scope,
    display,
    orientation,
    theme_color: pwa.themeColor ?? '#ffffff',
    background_color: pwa.backgroundColor ?? '#ffffff',
    icons: pwa.icons.map((icon) => ({
      src: icon.src,
      sizes: icon.sizes,
      type: icon.type ?? 'image/png',
      purpose: icon.purpose ?? 'any',
    })),
  }
  const cachePrefix = `spmpst-pwa-${siteId}-`
  const cacheName = `${cachePrefix}${createHash('sha256').update(JSON.stringify({ manifest, excludePaths })).digest('hex').slice(0, 10)}`
  const worker = `/* Generated by SPMPST from spmpst.pwa.json. */
const CACHE = ${JSON.stringify(cacheName)};
const CACHE_PREFIX = ${JSON.stringify(cachePrefix)};
const SCOPE = ${JSON.stringify(scope)};
const OFFLINE = ${JSON.stringify(offlinePath)};
const EXCLUDED = ${JSON.stringify(excludePaths)};
const isExcluded = (path) => EXCLUDED.some((prefix) => path.startsWith(prefix));
const cacheable = (response) => {
  if (!response || !response.ok || response.type !== 'basic') return false;
  const control = response.headers.get('Cache-Control') || '';
  if (/no-store|private/i.test(control)) return false;
  const length = Number(response.headers.get('Content-Length') || 0);
  return !length || length < 3 * 1024 * 1024;
};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.add(OFFLINE)));
  self.skipWaiting();
});
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE).map((key) => caches.delete(key)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(SCOPE) || isExcluded(url.pathname)) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).then((response) => {
      if (cacheable(response) && (response.headers.get('Content-Type') || '').includes('text/html')) {
        const copy = response.clone();
        event.waitUntil(caches.open(CACHE).then((cache) => cache.put(request, copy)));
      }
      return response;
    }).catch(async () => (await caches.match(request)) || (await caches.match(OFFLINE))));
    return;
  }
  if (url.search || /\\/(?:@vite|@id|node_modules)\\//.test(url.pathname) || !/\\.(?:css|js|mjs|woff2?|png|jpe?g|webp|svg|ico)$/i.test(url.pathname)) return;
  event.respondWith(caches.open(CACHE).then(async (cache) => {
    const cached = await cache.match(request);
    const update = fetch(request).then((response) => {
      if (cacheable(response)) cache.put(request, response.clone());
      return response;
    });
    return cached || update;
  }));
});
`
  const offline = `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="${escapeHtml(pwa.themeColor ?? '#ffffff')}"><title>${escapeHtml(pwa.shortName)} — Offline</title><style>body{font:16px/1.6 system-ui,sans-serif;max-width:38rem;margin:15vh auto;padding:0 1.25rem;color:#18212b}h1{line-height:1.2}a{color:#1769e0}@media(prefers-color-scheme:dark){body{background:#101820;color:#f3f6f8}a{color:#8db8ff}}</style><h1>You’re offline</h1><p>This page is not available yet. Reconnect to the internet and try again.</p><p><a href="${escapeHtml(startUrl)}">Return to ${escapeHtml(pwa.shortName)}</a></p></html>`
  for (const [url, body] of [[manifestPath, `${JSON.stringify(manifest, null, 2)}\n`], [workerPath, worker], [offlinePath, offline]]) {
    const target = resolve(generatedPublic, `.${url}`)
    if (!target.startsWith(`${resolve(generatedPublic)}/`)) fail(`generated path escapes public output: ${url}`)
    await mkdir(join(target, '..'), { recursive: true })
    generatedFiles.add(target)
    await writeIfChanged(target, body)
  }
}
