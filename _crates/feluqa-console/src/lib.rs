/// Register a concrete product host for one or more console profiles.
///
/// The console runner creates the host only after selecting a profile. This
/// keeps product-specific context construction out of `main`.
#[macro_export]
macro_rules! register_host {
    ($module:ident, $host:ty, $profiles:expr) => {
        mod $module {
            fn create(
                path: &::std::path::Path,
            ) -> ::core::result::Result<
                ::std::boxed::Box<dyn ::core::any::Any>,
                ::std::string::String,
            > {
                let host = <$host as $crate::ConsoleHost>::create(path)?;
                ::core::result::Result::Ok(::std::boxed::Box::new(host))
            }

            fn exit_code(host: &dyn ::core::any::Any) -> ::std::process::ExitCode {
                match host.downcast_ref::<$host>() {
                    ::core::option::Option::Some(host) => {
                        <$host as $crate::ConsoleHost>::exit_code(host)
                    }
                    ::core::option::Option::None => ::std::process::ExitCode::FAILURE,
                }
            }

            fn command_context(host: &dyn ::core::any::Any) -> &'static str {
                match host.downcast_ref::<$host>() {
                    ::core::option::Option::Some(host) => {
                        <$host as $crate::ConsoleHost>::command_context(host)
                    }
                    ::core::option::Option::None => "any",
                }
            }

            fn context_notice(
                host: &dyn ::core::any::Any,
                profile: &str,
            ) -> ::core::option::Option<&'static str> {
                match host.downcast_ref::<$host>() {
                    ::core::option::Option::Some(host) => {
                        <$host as $crate::ConsoleHost>::context_notice(host, profile)
                    }
                    ::core::option::Option::None => ::core::option::Option::None,
                }
            }

            fn supports_profile(profile: &str) -> bool {
                let mut declared_profiles = $profiles.iter();
                ::core::iter::Iterator::any(&mut declared_profiles, |declared| {
                    declared.id == profile
                })
            }

            $crate::inventory::submit! {
                $crate::ConsoleHostDescriptor {
                    supports_profile: supports_profile,
                    create,
                    exit_code,
                    command_context,
                    context_notice,
                }
            }
        }
    };
}

