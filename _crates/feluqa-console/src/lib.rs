/// Error encountered while creating or querying a command registry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RegistryError {
    /// Two commands or aliases resolve to the same path.
    DuplicatePath(String),
    /// No command matched the requested path.
    UnknownCommand(String),
    /// A command belongs to this profile but is unavailable in the current context.
    UnavailableInContext {
        /// Requested command path.
        path: String,
        /// Required command context.
        required: String,
        /// Detected product context.
        active: String,
    },
    /// A supplied profile is not configured by the product.
    UnknownProfile(String),
}

impl fmt::Display for RegistryError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DuplicatePath(path) => {
                write!(formatter, "duplicate console command path `{path}`")
            }
            Self::UnknownCommand(path) => write!(formatter, "unknown command `{path}`"),
            Self::UnavailableInContext {
                path,
                required,
                active,
            } => {
                let required = match required.as_str() {
                    "app" => "an application directory",
                    "workspace" => "a Feluqa workspace root",
                    "app-or-workspace" => "an application directory or workspace root",
                    other => other,
                };
                let active = match active.as_str() {
                    "app" => "an application directory",
                    "workspace" => "a Feluqa workspace root",
                    "global" => "a directory outside a Feluqa app and workspace",
                    other => other,
                };
                write!(
                    formatter,
                    "command `{path}` requires {required}; current location is {active}"
                )
            }
            Self::UnknownProfile(profile) => {
                write!(formatter, "unknown console profile `{profile}`")
            }
        }
    }
}

/// Deterministic view over the linked command inventory.
pub struct CommandRegistry {
    commands: Vec<&'static CommandDescriptor>,
}

impl CommandRegistry {
    /// Collect, sort and validate every linked command descriptor.
    pub fn discover() -> Result<Self, RegistryError> {
        let mut commands: Vec<&'static CommandDescriptor> =
            inventory::iter::<CommandDescriptor>().collect();
        commands.sort_by(|left, right| left.name.cmp(right.name));
        let mut paths: Vec<(&str, &CommandDescriptor)> = Vec::new();
        for command in &commands {
            for path in core::iter::once(command.name).chain(command.aliases.iter().copied()) {
                if paths.iter().any(|(existing, previous)| {
                    *existing == path && commands_share_profile(previous, command)
                }) {
                    return Err(RegistryError::DuplicatePath(path.to_string()));
                }
                paths.push((path, command));
            }
        }
        Ok(Self { commands })
    }

    /// List commands visible in a profile, sorted by canonical name.
    pub fn commands(&self, profile: &str, include_hidden: bool) -> Vec<&'static CommandDescriptor> {
        self.commands
            .iter()
            .copied()
            .filter(|command| {
                (include_hidden || !command.hidden) && command_belongs_to_profile(command, profile)
            })
            .collect()
    }

    /// List commands available to a profile in a product-defined context.
    pub fn commands_in_context(
        &self,
        profile: &str,
        include_hidden: bool,
        context: &str,
    ) -> Vec<&'static CommandDescriptor> {
        self.commands(profile, include_hidden)
            .into_iter()
            .filter(|command| context_matches(command.context, context))
            .collect()
    }

    /// Resolve a canonical path or alias for the selected profile.
    pub fn resolve(
        &self,
        profile: &str,
        path: &str,
    ) -> Result<&'static CommandDescriptor, RegistryError> {
        self.commands
            .iter()
            .copied()
            .find(|command| {
                command_belongs_to_profile(command, profile)
                    && (command.name == path || command.aliases.contains(&path))
            })
            .ok_or_else(|| RegistryError::UnknownCommand(path.to_string()))
    }

    /// Resolve a command only when it is available in the detected context.
    pub fn resolve_in_context(
        &self,
        profile: &str,
        path: &str,
        context: &str,
    ) -> Result<&'static CommandDescriptor, RegistryError> {
        match self.resolve(profile, path) {
            Ok(command) if context_matches(command.context, context) => Ok(command),
            Ok(command) => Err(RegistryError::UnavailableInContext {
                path: command.name.to_string(),
                required: command.context.to_string(),
                active: context.to_string(),
            }),
            Err(error) => Err(error),
        }
    }

    /// Print generated root or command help to stdout.
    #[cfg(feature = "std")]
    pub fn print_help(
        &self,
        profile: &str,
        product: &str,
        topic: Option<&str>,
        include_hidden: bool,
    ) -> Result<(), RegistryError> {
        self.print_help_in_context(profile, product, topic, include_hidden, "any")
    }

    /// Print help filtered to the product's detected execution context.
    #[cfg(feature = "std")]
    pub fn print_help_in_context(
        &self,
        profile: &str,
        product: &str,
        topic: Option<&str>,
        include_hidden: bool,
        context: &str,
    ) -> Result<(), RegistryError> {
        self.print_help_in_context_with_notice(
            profile,
            product,
            topic,
            include_hidden,
            context,
            None,
        )
    }

    /// Print context-filtered help with a notice supplied by the product host.
    #[cfg(feature = "std")]
    pub fn print_help_in_context_with_notice(
        &self,
        profile: &str,
        product: &str,
        topic: Option<&str>,
        include_hidden: bool,
        context: &str,
        notice: Option<&str>,
    ) -> Result<(), RegistryError> {
        use std::io::{self, Write};
        let mut output = io::stdout().lock();
        if let Some(topic) = topic {
            match self.resolve_in_context(profile, topic, context) {
                Ok(command) => {
                    writeln!(
                        output,
                        "{}",
                        terminal::paint(
                            command.usage.unwrap_or(command.name),
                            terminal::Color::Cyan
                        )
                    )
                    .map_err(io_error)?;
                    writeln!(
                        output,
                        "\n{}",
                        terminal::paint(command.description, terminal::Color::Muted)
                    )
                    .map_err(io_error)?;
                    if !command.aliases.is_empty() {
                        writeln!(
                            output,
                            "{} {}",
                            terminal::paint("Aliases:", terminal::Color::Muted),
                            command.aliases.join(", ")
                        )
                        .map_err(io_error)?;
                    }
                    return Ok(());
                }
                Err(error @ RegistryError::UnavailableInContext { .. }) => return Err(error),
                Err(_) => {}
            }
            let children: Vec<&'static CommandDescriptor> = self
                .commands_in_context(profile, include_hidden, context)
                .into_iter()
                .filter(|command| {
                    command.name.starts_with(topic)
                        && command.name.as_bytes().get(topic.len()) == Some(&b' ')
                })
                .collect();
            if !children.is_empty() {
                writeln!(
                    output,
                    "{} {}\n",
                    terminal::paint(product, terminal::Color::Accent),
                    topic
                )
                .map_err(io_error)?;
                for command in children {
                    writeln!(
                        output,
                        "{}",
                        terminal::command_entry(command.name, command.description)
                    )
                    .map_err(io_error)?;
                }
                return Ok(());
            }
            return Err(RegistryError::UnknownCommand(topic.to_string()));
        }
        if let Some(notice) = notice {
            write!(
                output,
                "{}",
                terminal::status_block(notice, terminal::OutputStyle::Info)
            )
            .map_err(io_error)?;
        } else {
            writeln!(output).map_err(io_error)?;
        }
        writeln!(
            output,
            "{}\n",
            terminal::paint(
                &alloc::format!("Usage: {product} [-i|--interactive] <command> [arguments]"),
                terminal::Color::Muted
            )
        )
        .map_err(io_error)?;
        for command in self.commands_in_context(profile, include_hidden, context) {
            let aliases = if command.aliases.is_empty() {
                String::new()
            } else {
                alloc::format!("  aliases: {}", command.aliases.join(", "))
            };
            writeln!(
                output,
                "{}",
                terminal::command_entry(
                    command.name,
                    &alloc::format!("{}{aliases}", command.description)
                )
            )
            .map_err(io_error)?;
        }
        writeln!(
            output,
            "\n{}",
            terminal::paint(
                &alloc::format!(
                    "Use `{product} --interactive` to open the command chooser. Run `{product} help <command>` for details."
                ),
                terminal::Color::Muted
            )
        )
        .map_err(io_error)?;
        Ok(())
    }

    /// Print the profile header followed by its generated help.
    #[cfg(feature = "std")]
    pub fn print_profile_help(
        &self,
        profile: &Profile,
        topic: Option<&str>,
        include_hidden: bool,
    ) -> Result<(), RegistryError> {
        self.print_profile_help_in_context(profile, topic, include_hidden, "any")
    }

    /// Print a profile header and help filtered to the detected product context.
    #[cfg(feature = "std")]
    pub fn print_profile_help_in_context(
        &self,
        profile: &Profile,
        topic: Option<&str>,
        include_hidden: bool,
        context: &str,
    ) -> Result<(), RegistryError> {
        self.print_profile_help_in_context_with_notice(
            profile,
            topic,
            include_hidden,
            context,
            None,
        )
    }

    /// Print profile help with a notice supplied by the product host.
    #[cfg(feature = "std")]
    pub fn print_profile_help_in_context_with_notice(
        &self,
        profile: &Profile,
        topic: Option<&str>,
        include_hidden: bool,
        context: &str,
        notice: Option<&str>,
    ) -> Result<(), RegistryError> {
        use std::io::{self, Write};
        if !profile.header.is_empty() {
            let mut output = io::stdout().lock();
            writeln!(output, "{}", profile.header).map_err(io_error)?;
        }
        self.print_help_in_context_with_notice(
            profile.id,
            profile.binary_name,
            topic,
            include_hidden,
            context,
            notice,
        )
    }
}

fn command_belongs_to_profile(command: &CommandDescriptor, profile: &str) -> bool {
    let mut prefix = String::from("__feluqa_command_");
    prefix.push_str(&profile.chars().count().to_string());
    prefix.push('_');
    for character in profile.chars() {
        prefix.push(if character.is_ascii_alphanumeric() {
            character.to_ascii_lowercase()
        } else {
            '_'
        });
    }
    prefix.push('_');
    command
        .module_path
        .split("::")
        .any(|component| component.starts_with(&prefix))
}

fn commands_share_profile(left: &CommandDescriptor, right: &CommandDescriptor) -> bool {
    match (command_profile(left), command_profile(right)) {
        (Some(left), Some(right)) => left == right,
        _ => true,
    }
}

fn command_profile(command: &CommandDescriptor) -> Option<String> {
    command
        .module_path
        .split("::")
        .find_map(|component| component.strip_prefix("__feluqa_command_"))
        .and_then(|component| {
            let (length, rest) = component.split_once('_')?;
            let length = length.parse::<usize>().ok()?;
            Some(rest.chars().take(length).collect())
        })
}

fn context_matches(required: &str, active: &str) -> bool {
    matches!(required, "any" | "anywhere")
        || required == active
        || (required == "in_dev" && active == "in_app")
}

/// Parse a command path by selecting the longest registered path prefix.
pub fn parse<'a>(
    registry: &CommandRegistry,
    profile: &str,
    words: &'a [String],
) -> Result<ParsedCommand<'a>, RegistryError> {
    parse_descriptors(registry.commands(profile, true), words)
}

/// Parse only commands available in the selected product context.
pub fn parse_in_context<'a>(
    registry: &CommandRegistry,
    profile: &str,
    words: &'a [String],
    context: &str,
) -> Result<ParsedCommand<'a>, RegistryError> {
    match parse_descriptors(registry.commands_in_context(profile, true, context), words) {
        Ok(parsed) => Ok(parsed),
        Err(error) => match parse_descriptors(registry.commands(profile, true), words) {
            Ok(parsed) => Err(RegistryError::UnavailableInContext {
                path: parsed.descriptor.name.to_string(),
                required: parsed.descriptor.context.to_string(),
                active: context.to_string(),
            }),
            Err(_) => Err(error),
        },
    }
}

fn parse_descriptors<'a>(
    commands: Vec<&'static CommandDescriptor>,
    words: &'a [String],
) -> Result<ParsedCommand<'a>, RegistryError> {
    let mut best: Option<(&'static CommandDescriptor, usize)> = None;
    for descriptor in commands {
        for path in core::iter::once(descriptor.name).chain(descriptor.aliases.iter().copied()) {
            let parts: Vec<&str> = path.split(' ').collect();
            if parts.len() <= words.len()
                && parts
                    .iter()
                    .zip(words.iter())
                    .all(|(part, word)| *part == word.as_str())
                && best.map(|(_, length)| parts.len() > length).unwrap_or(true)
            {
                best = Some((descriptor, parts.len()));
            }
        }
    }
    match best {
        Some((descriptor, consumed)) => Ok(ParsedCommand {
            descriptor,
            arguments: &words[consumed..],
        }),
        None => Err(RegistryError::UnknownCommand(words.join(" "))),
    }
}

