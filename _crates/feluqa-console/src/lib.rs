/// Product-provided state initialized once before dispatching a console command.
#[cfg(feature = "std")]
pub trait ConsoleHost: Any {
    /// Create host state for the current working directory.
    fn create(current_directory: &std::path::Path) -> Result<Self, String>
    where
        Self: core::marker::Sized;

    /// Process status selected by the dispatched command.
    fn exit_code(&self) -> std::process::ExitCode;

    /// Context used to filter commands and contextual help.
    fn command_context(&self) -> &'static str {
        "any"
    }

    /// Optional product-defined startup/help notice for the selected profile.
    fn context_notice(&self, _profile: &str) -> Option<&'static str> {
        None
    }
}

/// Erased host factory submitted by a product for selected profiles.
#[cfg(feature = "std")]
pub struct ConsoleHostDescriptor {
    /// Check whether the declared profile table uses this host factory.
    pub supports_profile: fn(&str) -> bool,
    /// Create this profile's host from the working directory.
    pub create: fn(&std::path::Path) -> Result<std::boxed::Box<dyn Any>, String>,
    /// Read the process status selected by a command.
    pub exit_code: fn(&dyn Any) -> std::process::ExitCode,
    /// Read the product-defined command context from a host instance.
    pub command_context: fn(&dyn Any) -> &'static str,
    /// Product-defined notice for the profile and detected host context.
    pub context_notice: fn(&dyn Any, &str) -> Option<&'static str>,
}

#[cfg(feature = "std")]
inventory::collect!(ConsoleHostDescriptor);

#[cfg(feature = "std")]
impl MakeConsole {
    /// Configure the console from the product's profile declarations.
    pub const fn new(profiles: &'static [Profile]) -> Self {
        Self { profiles }
    }

    /// Run this console from the current process arguments and executable name.
    /// The selected profile's host factory is resolved from the linked registry.
    pub fn run(&self) -> std::process::ExitCode {
        use std::ffi::OsString;
        use std::iter::Iterator;
        let mut arguments = std::env::args_os();
        let binary_name = arguments
            .next()
            .and_then(|path| {
                std::path::PathBuf::from(path)
                    .file_name()
                    .map(OsString::from)
            })
            .and_then(|name| name.into_string().ok())
            .unwrap_or_else(|| String::from("feluqa"));
        self.run_registered(&binary_name, arguments)
    }

    /// Run an explicitly named executable profile using linked host factories.
    pub fn run_registered<I>(&self, binary_name: &str, arguments: I) -> std::process::ExitCode
    where
        I: IntoIterator<Item = std::ffi::OsString>,
    {
        use std::ffi::OsString;
        use std::process::ExitCode;
        let arguments = match arguments
            .into_iter()
            .map(|argument: OsString| {
                argument
                    .into_string()
                    .map_err(|_| String::from("command arguments must be valid UTF-8"))
            })
            .collect::<Result<Vec<String>, String>>()
        {
            Ok(arguments) => arguments,
            Err(error) => {
                terminal::error(&error);
                return ExitCode::FAILURE;
            }
        };
        let (requested, _, _) = match selected_profile(&arguments) {
            Ok(selected) => selected,
            Err(error) => {
                terminal::error(&error);
                return ExitCode::FAILURE;
            }
        };
        let profiles = match Profiles::new(self.profiles) {
            Ok(profiles) => profiles,
            Err(error) => {
                terminal::error(&alloc::format!("{error}"));
                return ExitCode::FAILURE;
            }
        };
        let profile = match profiles.select(requested.as_deref(), Some(binary_name)) {
            Ok(profile) => profile,
            Err(error) => {
                terminal::error(&alloc::format!("{error}"));
                return ExitCode::FAILURE;
            }
        };
        let host_factory = inventory::iter::<ConsoleHostDescriptor>()
            .find(|provider| (provider.supports_profile)(&profile.id));
        let current = match std::env::current_dir() {
            Ok(directory) => directory,
            Err(error) => {
                terminal::error(&std::format!("could not read current directory: {error}"));
                return ExitCode::FAILURE;
            }
        };
        let mut host: std::boxed::Box<dyn Any> = match host_factory {
            Some(provider) => match (provider.create)(&current) {
                Ok(host) => host,
                Err(error) => {
                    terminal::error(&error);
                    return ExitCode::FAILURE;
                }
            },
            None => {
                #[cfg(feature = "platform")]
                {
                    match platform::FeluqaHost::new(&current) {
                        Ok(host) => std::boxed::Box::new(host),
                        Err(error) => {
                            terminal::error(&error);
                            return ExitCode::FAILURE;
                        }
                    }
                }
                #[cfg(not(feature = "platform"))]
                {
                    std::boxed::Box::new(())
                }
            }
        };
        let active_context = host_factory
            .map(|provider| (provider.command_context)(&*host))
            .or_else(|| {
                #[cfg(feature = "platform")]
                {
                    host.downcast_ref::<platform::FeluqaHost>()
                        .map(ConsoleHost::command_context)
                }
                #[cfg(not(feature = "platform"))]
                {
                    None
                }
            })
            .unwrap_or("outside");
        let notice = host_factory
            .and_then(|provider| (provider.context_notice)(&*host, profile.id))
            .or_else(|| {
                #[cfg(feature = "platform")]
                {
                    host.downcast_ref::<platform::FeluqaHost>()
                        .and_then(|host| ConsoleHost::context_notice(host, profile.id))
                }
                #[cfg(not(feature = "platform"))]
                {
                    None
                }
            });
        match run_in_context_with_notice(
            self.profiles,
            binary_name,
            &arguments,
            &mut *host,
            active_context,
            notice,
        ) {
            Ok(()) => host_factory
                .map(|provider| (provider.exit_code)(&*host))
                .or_else(|| {
                    #[cfg(feature = "platform")]
                    {
                        host.downcast_ref::<platform::FeluqaHost>()
                            .map(ConsoleHost::exit_code)
                    }
                    #[cfg(not(feature = "platform"))]
                    {
                        None
                    }
                })
                .unwrap_or(ExitCode::SUCCESS),
            Err(error) => finish_console_error(&error),
        }
    }

    /// Run a named executable profile with operating-system arguments.
    pub fn run_as<H, I>(&self, binary_name: &str, arguments: I) -> std::process::ExitCode
    where
        H: ConsoleHost,
        I: IntoIterator<Item = std::ffi::OsString>,
    {
        self.run_process(
            binary_name,
            arguments,
            || {
                let current = std::env::current_dir()
                    .map_err(|error| std::format!("could not read current directory: {error}"))?;
                H::create(&current)
            },
            ConsoleHost::exit_code,
        )
    }

    /// Run the selected executable profile with operating-system arguments.
    /// The host factory is evaluated only after arguments are known to be UTF-8.
    pub fn run_process<H, I, F, G>(
        &self,
        binary_name: &str,
        arguments: I,
        create_host: F,
        exit_code: G,
    ) -> std::process::ExitCode
    where
        H: Any,
        I: IntoIterator<Item = std::ffi::OsString>,
        F: core::ops::FnOnce() -> Result<H, String>,
        G: core::ops::FnOnce(&H) -> std::process::ExitCode,
    {
        use std::ffi::OsString;
        use std::process::ExitCode;
        let arguments = match arguments
            .into_iter()
            .map(|argument: OsString| {
                argument
                    .into_string()
                    .map_err(|_| String::from("command arguments must be valid UTF-8"))
            })
            .collect::<Result<Vec<String>, String>>()
        {
            Ok(arguments) => arguments,
            Err(error) => {
                terminal::error(&error);
                return ExitCode::FAILURE;
            }
        };
        let mut host = match create_host() {
            Ok(host) => host,
            Err(error) => {
                terminal::error(&error);
                return ExitCode::FAILURE;
            }
        };
        match run(self.profiles, binary_name, &arguments, &mut host) {
            Ok(()) => exit_code(&host),
            Err(error) => finish_console_error(&error),
        }
    }
}

#[cfg(feature = "std")]
fn finish_console_error(error: &str) -> std::process::ExitCode {
    use std::process::ExitCode;

    match error {
        "selection cancelled" => {
            terminal::warning("selection cancelled");
            ExitCode::SUCCESS
        }
        "interrupted" => {
            terminal::warning("interrupted");
            ExitCode::from(130)
        }
        "terminated" => {
            terminal::warning("terminated");
            ExitCode::from(143)
        }
        _ => {
            terminal::error(error);
            ExitCode::FAILURE
        }
    }
}

/// Run a registered command for the selected profile, or print generated help.
/// The product supplies its own command host as opaque state; console owns
/// profile selection, command lookup, aliases, help and handler dispatch.
#[cfg(feature = "std")]
pub fn run(
    profiles: &'static [Profile],
    binary_name: &str,
    arguments: &[String],
    host: &mut dyn Any,
) -> Result<(), String> {
    run_in_context(profiles, binary_name, arguments, host, "any")
}

/// Dispatch a command after filtering help, discovery and resolution by context.
#[cfg(feature = "std")]
pub fn run_in_context(
    profiles: &'static [Profile],
    binary_name: &str,
    arguments: &[String],
    host: &mut dyn Any,
    command_context: &str,
) -> Result<(), String> {
    run_in_context_with_notice(
        profiles,
        binary_name,
        arguments,
        host,
        command_context,
        None,
    )
}

#[cfg(feature = "std")]
fn run_in_context_with_notice(
    profiles: &'static [Profile],
    binary_name: &str,
    arguments: &[String],
    host: &mut dyn Any,
    command_context: &str,
    notice: Option<&'static str>,
) -> Result<(), String> {
    let profiles = Profiles::new(profiles).map_err(|error| error.to_string())?;
    let (requested, interactive_requested, arguments) = selected_profile(arguments)?;
    let profile = profiles
        .select(requested.as_deref(), Some(binary_name))
        .map_err(|error| error.to_string())?;
    let registry = CommandRegistry::discover().map_err(|error| error.to_string())?;
    if interactive_requested && !terminal::interactive() {
        return Err(String::from(
            "interactive mode requires a terminal; pass all command arguments for CI or automation",
        ));
    }
    let is_help = arguments.is_empty()
        || arguments
            .first()
            .is_some_and(|word| matches!(word.as_str(), "--help" | "-h" | "help"))
        || arguments
            .iter()
            .any(|word| matches!(word.as_str(), "--help" | "-h"));
    if interactive_requested && arguments.is_empty() {
        if !profile.header.is_empty() {
            terminal::echo(profile.header, terminal::OutputStyle::Plain);
            if notice.is_none() {
                terminal::blankline();
            }
        }
        print_startup_notice(notice);
    } else if !is_help {
        print_startup_notice(notice);
    }
    let parsed = if interactive_requested && arguments.is_empty() {
        let commands = registry.commands_in_context(profile.id, false, command_context);
        let selected = choose_command(&commands, "What would you like to do?")?;
        ParsedCommand {
            descriptor: commands[selected],
            arguments,
        }
    } else if arguments.is_empty()
        || matches!(arguments.first().map(String::as_str), Some("--help" | "-h"))
    {
        registry
            .print_profile_help_in_context_with_notice(
                profile,
                None,
                arguments.iter().any(|word| word == "--all"),
                command_context,
                notice,
            )
            .map_err(|error| error.to_string())?;
        return Ok(());
    } else if arguments.first().is_some_and(|word| word == "help") {
        let topic = arguments
            .get(1..)
            .unwrap_or_default()
            .iter()
            .filter(|word| word.as_str() != "--all")
            .map(String::as_str)
            .collect::<Vec<_>>()
            .join(" ");
        let topic = if topic.is_empty() {
            None
        } else {
            Some(topic.as_str())
        };
        registry
            .print_profile_help_in_context_with_notice(
                profile,
                topic,
                arguments.iter().any(|word| word == "--all"),
                command_context,
                notice,
            )
            .map_err(|error| error.to_string())?;
        return Ok(());
    } else if let Some(help_at) = arguments
        .iter()
        .position(|word| word == "--help" || word == "-h")
    {
        let topic = arguments[..help_at]
            .iter()
            .map(String::as_str)
            .collect::<Vec<_>>()
            .join(" ");
        let topic = if topic.is_empty() {
            None
        } else {
            Some(topic.as_str())
        };
        registry
            .print_profile_help_in_context_with_notice(
                profile,
                topic,
                false,
                command_context,
                notice,
            )
            .map_err(|error| error.to_string())?;
        return Ok(());
    } else {
        match parse_in_context(&registry, profile.id, arguments, command_context) {
            Ok(parsed) => parsed,
            Err(RegistryError::UnknownCommand(_)) => {
                let prefix = arguments.join(" ");
                let commands = registry
                    .commands_in_context(profile.id, false, command_context)
                    .into_iter()
                    .filter(|command| {
                        command.name.starts_with(&prefix)
                            && (command.name.len() > prefix.len() || command.name == prefix)
                    })
                    .collect::<Vec<_>>();
                if commands.is_empty() {
                    return Err(RegistryError::UnknownCommand(prefix).to_string());
                }
                if interactive_requested {
                    let selected = choose_command(&commands, "Choose a command:")?;
                    ParsedCommand {
                        descriptor: commands[selected],
                        arguments: &arguments[arguments.len()..],
                    }
                } else if commands.len() == 1 {
                    return Err(alloc::format!(
                        "unknown command `{prefix}`. Did you mean `{}`?",
                        commands[0].name
                    ));
                } else {
                    let choices = commands
                        .iter()
                        .map(|command| command.name)
                        .collect::<Vec<_>>()
                        .join(", ");
                    return Err(alloc::format!(
                        "unknown command prefix `{prefix}`. Available commands: {choices}"
                    ));
                }
            }
            Err(error) => return Err(error.to_string()),
        }
    };
    let mut context = CommandContext::new_in_context_with_notice(
        profile.id,
        command_context,
        notice,
        parsed.arguments,
        host,
    );
    (parsed.descriptor.handler)(&mut context).map_err(|error| error.to_string())
}

#[cfg(feature = "std")]
fn print_startup_notice(notice: Option<&str>) {
    if let Some(notice) = notice {
        terminal::info(notice);
    }
}

#[cfg(feature = "std")]
fn choose_command(commands: &[&'static CommandDescriptor], prompt: &str) -> Result<usize, String> {
    if commands.is_empty() {
        return Err(String::from("no commands are available in this context"));
    }
    let labels = commands
        .iter()
        .map(|command| alloc::format!("{} — {}", command.name, command.description))
        .collect::<Vec<String>>();
    let options = labels.iter().map(String::as_str).collect::<Vec<_>>();
    terminal::select(prompt, &options, 0)
}

#[cfg(feature = "std")]
fn selected_profile(arguments: &[String]) -> Result<(Option<String>, bool, &[String]), String> {
    let mut index = 0;
    let mut selected = None;
    let mut interactive = false;
    while let Some(argument) = arguments.get(index) {
        if let Some(value) = argument.strip_prefix("--profile=") {
            if value.is_empty() {
                return Err(String::from("`--profile=` needs a profile name"));
            }
            selected = Some(value.to_string());
            index += 1;
        } else if argument == "--profile" {
            let value = arguments
                .get(index + 1)
                .ok_or_else(|| String::from("`--profile` needs a profile name"))?;
            selected = Some(value.clone());
            index += 2;
        } else if matches!(
            argument.as_str(),
            "-i" | "-int" | "--interactive" | "--interactif"
        ) {
            interactive = true;
            index += 1;
        } else {
            break;
        }
    }
    Ok((selected, interactive, &arguments[index..]))
}

impl Profiles {
    /// Create a profile set and verify unique IDs and aliases.
    pub fn new(entries: &'static [Profile]) -> Result<Self, RegistryError> {
        for (index, profile) in entries.iter().enumerate() {
            if entries[..index].iter().any(|previous| {
                previous.id == profile.id
                    || previous
                        .launch_aliases
                        .iter()
                        .any(|alias| profile.launch_aliases.contains(alias))
            }) {
                return Err(RegistryError::DuplicatePath(profile.id.to_string()));
            }
        }
        Ok(Self { entries })
    }

    /// Resolve an ID or executable alias; `default` is the first entry.
    pub fn select(
        &self,
        requested: Option<&str>,
        executable: Option<&str>,
    ) -> Result<&'static Profile, RegistryError> {
        let selected = requested
            .or_else(|| {
                executable.and_then(|name| {
                    self.entries
                        .iter()
                        .find(|profile| {
                            profile.binary_name == name || profile.launch_aliases.contains(&name)
                        })
                        .map(|profile| profile.id)
                })
            })
            .or_else(|| self.entries.first().map(|profile| profile.id))
            .ok_or_else(|| {
                RegistryError::UnknownProfile(String::from("no profiles are configured"))
            })?;
        self.entries
            .iter()
            .find(|profile| profile.id == selected)
            .ok_or_else(|| RegistryError::UnknownProfile(selected.to_string()))
    }
}

#[cfg(feature = "std")]
fn io_error(error: std::io::Error) -> RegistryError {
    RegistryError::UnknownCommand(error.to_string())
}
